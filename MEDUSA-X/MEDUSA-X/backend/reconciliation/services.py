import re

from records.models import ClinicalDocument
from .models import ReconciliationIssue


AUTO_NOTE = "AUTO_DIAGNOSIS_REVIEW"


def extract_diagnosis(text):
    """
    Extract explicitly labelled diagnosis statements.
    This is a basic rule-based extractor, not an AI diagnosis.
    """

    patterns = [
        r"^\s*(?:final|primary|provisional|working)?\s*diagnos(?:is|es)\s*[:\-]\s*(.+?)\s*$",
    ]

    found = []

    for pattern in patterns:
        matches = re.findall(pattern, text, flags=re.IGNORECASE | re.MULTILINE)

        for match in matches:
            value = match.strip(" .,:;-")

            if not value:
                continue

            if value.lower() in [
                "none",
                "nil",
                "unknown",
                "not available",
                "no diagnosis",
            ]:
                continue

            if value not in found:
                found.append(value)

    return found


def run_diagnosis_reconciliation(patient_id):

    documents = ClinicalDocument.objects.filter(
        patient_id=patient_id,
        status="EXTRACTED"
    ).exclude(extracted_text="")

    diagnoses = []

    for document in documents:

        extracted = extract_diagnosis(document.extracted_text)

        for diagnosis in extracted:

            diagnoses.append({
                "document": document.title,
                "diagnosis": diagnosis,
                "document_id": document.id,
            })

    # Compare distinct diagnosis statements across documents.
    unique_diagnoses = {}

    for item in diagnoses:
        key = item["diagnosis"].strip().lower()
        unique_diagnoses.setdefault(key, item)

    auto_issues = ReconciliationIssue.objects.filter(
        patient_id=patient_id,
        issue_type="DIAGNOSIS",
        reviewer_note__startswith=AUTO_NOTE,
        resolved=False,
    )

    if len(unique_diagnoses) < 2:
        auto_issues.delete()
        return

    evidence = "\n".join([
        f"Document: {item['document']}\n"
        f"Diagnosis: {item['diagnosis']}"
        for item in unique_diagnoses.values()
    ])

    description = (
        "Different diagnosis statements were found across this patient's "
        "clinical documents. These may represent a discrepancy or "
        "coexisting conditions. Clinician verification is required."
    )

    issue = auto_issues.first()

    if issue:
        issue.description = description
        issue.evidence = evidence
        issue.save(update_fields=["description", "evidence"])
    else:
        ReconciliationIssue.objects.create(
            patient_id=patient_id,
            issue_type="DIAGNOSIS",
            description=description,
            evidence=evidence,
            reviewer_note=(
                AUTO_NOTE +
                ": Automatically generated by the rule-based "
                "document reconciliation engine. Requires clinician review."
            ),
            resolved=False,
        )